* Display score
prscore
 ldd score
 bsr fmtnum	; format number and return u pointer to string
 ldd #4		; x position
 bsr prstring
 rts

* Display string
*
* U string
* B X coord
prstring
 ldx #SCREEN+64	; second row of screen
 leax b,x	; now X points to starting screen byte
loop@
 lda ,u		; get next character
 anda #$7f	; strip off high bit
 bsr findchar	; point Y to pixel data
 lda #5		; 5 rows
 pshs a
loop1@
 bsr row	; display one row of font data
 leay 1,y	; next row of font data
 leax 64,x	; point to next screen row
 dec ,s
 bne loop1@
 leax -64*5+3,x	; position for next character on line
 leas 1,s
 tst ,u+	; done?
 bpl loop@
 rts

