* Entry:
*	A ASCII character
* Exit:
*	Y pointer to font data
findchar
 pshs x
 leay font,pcr
 leax charset,pcr
loop@
 cmpa ,x+	; found in charset?
 beq endloop@
 leay 5,y	; advance to next font data
 bra loop@
endloop@
 puls x,pc
 
* Entry:
*	D number
* Exit:
*	U pointer to string
*
fmtnum	ldu #value
	std number
	ldd #10000
	bsr digit
	ldd #1000
	bsr digit
	ldd #100
	bsr digit
	ldd #10
	bsr digit
	ldd #1
	bsr digit
	ldb #$80	; set bit on last digit
	orb -1,u
	stb -1,u
	ldu #value	; return pointer to value
	ldb #5
loop@	lda ,u
	cmpa #'0'	; suppress zeroes
	bne exit@
	leau 1,u
	decb
	bgt loop@
exit@	rts

digit	pshs d
	lda #'0'
	sta ,u
	ldd number
loop@	subd ,s
	blt done@
	std number
	inc ,u
	bra loop@
done@	leau 1,u
	leas 2,s
	rts

